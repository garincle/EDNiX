#!/usr/bin/env bash
# Builds the EDNiX Python environment (venvEDNiX) from the validated, pinned versions.
#
#   bash Tools/setup_venv.sh                 venv <EDNiX>/venvEDNiX from requirements-lock.txt (exact versions)
#   bash Tools/setup_venv.sh --unlocked      newest versions allowed by requirements.txt (to test an upgrade)
#   bash Tools/setup_venv.sh --cpu           PyTorch CPU-only build (no CUDA libraries, ~2.5 GB smaller)
#   bash Tools/setup_venv.sh --dev           also pytest + pytest-xdist (test suite)
#   bash Tools/setup_venv.sh --venv DIR --python python3.11
#   bash Tools/setup_venv.sh --freeze        write requirements-lock.txt from an existing, validated venv
#
# <EDNiX>/venvEDNiX is where Exemples/Study_EDNiX/EDNiX_orchestrator.py and GUI/launch_EDNiX_GUI.sh look
# for the interpreter. The U-Net skull-stripping (muSkullStrip.py) runs with the `python3` found on the PATH:
# activate the venv (source venvEDNiX/bin/activate) before running a launcher.
#
# Non-pip requirements (not installed here): Singularity/Apptainer + the .sif images (AFNI, FSL, FreeSurfer,
# Connectome Workbench, ITK-SNAP, SynthStrip, TPCCLIB), the NHP-BrainExtraction U-Net models, optional
# `petpvc` on the PATH. See docs/installation.md.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VENV="$REPO/venvEDNiX"
PY="${PYTHON:-python3}"
LOCKED=1; CPU=0; DEV=0; FREEZE=0
TORCH_CPU_INDEX="https://download.pytorch.org/whl/cpu"

while [ $# -gt 0 ]; do
  case "$1" in
    --venv)     VENV="$(realpath -m "$2")"; shift 2;;
    --python)   PY="$2"; shift 2;;
    --unlocked) LOCKED=0; shift;;
    --cpu)      CPU=1; shift;;
    --dev)      DEV=1; shift;;
    --freeze)   FREEZE=1; shift;;
    -h|--help)  sed -n '2,18p' "$0"; exit 0;;
    *) echo "unknown option: $1 (see --help)"; exit 2;;
  esac
done

LOCK="$REPO/requirements-lock.txt"
REQ="$REPO/requirements.txt"

# ---------------------------------------------------------------- --freeze: lock = the validated venv
if [ "$FREEZE" = 1 ]; then
  [ -x "$VENV/bin/python" ] || { echo "no venv at $VENV (use --venv DIR)"; exit 1; }
  pyv="$("$VENV/bin/python" -c 'import platform; print(platform.python_version())')"
  {
    echo "# EDNiX validated environment: exact versions (pip freeze of $(basename "$VENV"), Python $pyv)."
    echo "# Generated by: bash Tools/setup_venv.sh --freeze --venv <venv>   on $(date +%F)"
    echo "# Install with: bash Tools/setup_venv.sh"
    # local +cuXXX / +cpu tags dropped so the same lock installs the CPU or the CUDA build of torch;
    # editable / direct-URL lines dropped (not reproducible from PyPI).
    "$VENV/bin/python" -m pip freeze --exclude-editable --all \
      | grep -vE '^(pip|setuptools|wheel|pytest|pytest-xdist|execnet|iniconfig|pluggy)==' \
      | grep -v ' @ ' | sed -E 's/\+(cu[0-9]+|cpu|rocm[0-9.]+)$//' | LC_ALL=C sort -f
  } > "$LOCK"
  echo "wrote $LOCK ($(grep -c '==' "$LOCK") packages, Python $pyv)"
  "$VENV/bin/python" "$REPO/Tools/check_requirements.py" || true
  exit 0
fi

# ---------------------------------------------------------------- build
"$PY" -c 'import sys; sys.exit(sys.version_info < (3, 10))' \
  || { echo "Python >= 3.10 required ($PY is $("$PY" -V 2>&1))"; exit 1; }
if [ -e "$VENV" ]; then
  echo "$VENV exists: remove it or choose another --venv (nothing changed)."; exit 1
fi
echo "[EDNiX] creating $VENV with $("$PY" -V 2>&1)"
"$PY" -m venv "$VENV"
VPY="$VENV/bin/python"
"$VPY" -m pip install --quiet --upgrade pip

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
if [ "$LOCKED" = 1 ]; then
  [ -f "$LOCK" ] || { echo "missing $LOCK (use --unlocked)"; exit 1; }
  SRC="$LOCK"
else
  SRC="$REQ"
fi
cp "$SRC" "$TMP/reqs.txt"

if [ "$CPU" = 1 ]; then
  # CUDA runtime wheels are only dependencies of the CUDA build of torch
  grep -vE '^(nvidia-[a-z0-9-]+|triton|cuda-[a-z0-9-]+)[=<>~ ;]' "$SRC" > "$TMP/all.txt" || true
  grep -E '^torch[=<>~ ;]' "$TMP/all.txt" > "$TMP/torch.txt" || echo torch > "$TMP/torch.txt"
  grep -vE '^torch[=<>~ ;]' "$TMP/all.txt" > "$TMP/reqs.txt"
  echo "[EDNiX] torch, CPU build: $(grep -v '^#' "$TMP/torch.txt" | tr '\n' ' ')"
  "$VPY" -m pip install --quiet --no-deps --index-url "$TORCH_CPU_INDEX" -r "$TMP/torch.txt"
fi

echo "[EDNiX] installing $(grep -c '^[A-Za-z]' "$TMP/reqs.txt") packages from $(basename "$SRC")"
if [ "$LOCKED" = 1 ]; then
  "$VPY" -m pip install --quiet --no-deps -r "$TMP/reqs.txt"   # the lock is complete: no resolution
else
  "$VPY" -m pip install --quiet -r "$TMP/reqs.txt"
fi
[ "$DEV" = 1 ] && "$VPY" -m pip install --quiet pytest pytest-xdist

# ---------------------------------------------------------------- verification
"$VPY" -m pip check
"$VPY" - <<'EOF'
import importlib
mods = ['numpy', 'scipy', 'pandas', 'openpyxl', 'joblib', 'tqdm', 'nibabel', 'nilearn', 'ants', 'nipype',
        'nitransforms', 'bids', 'pydicom', 'skimage', 'sklearn', 'statsmodels', 'patsy', 'pygam', 'nitime',
        'torch', 'matplotlib', 'seaborn', 'lxml']
bad = []
for m in mods:
    try:
        importlib.import_module(m)
    except Exception as e:
        bad.append(f'{m}: {e}')
if bad:
    raise SystemExit('import failed:\n  ' + '\n  '.join(bad))
import torch
print('[EDNiX] all imports OK; torch', torch.__version__, '| CUDA available:', torch.cuda.is_available())
EOF
"$VPY" "$REPO/Tools/check_requirements.py"
"$VPY" -m pip freeze --all > "$VENV/ednix-freeze.txt"
echo "[EDNiX] done. Activate with: source $VENV/bin/activate   (installed versions: $VENV/ednix-freeze.txt)"
for prog in singularity apptainer petpvc; do
  command -v "$prog" >/dev/null && echo "  found $prog" || echo "  not on PATH: $prog"
done
